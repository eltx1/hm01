    |            "failover", "roundrobin"
    |
    */

    'mailers' => [

        'smtp' => [
            'transport' => 'smtp',
            'scheme' => in_array(strtolower(trim((string) env('MAIL_SCHEME', ''))), ['smtp', 'smtps'], true)
